const TABLES: Record<Lang, Record<Key, string>> = { es: ES, en: EN, de: DE, pt: PT, ru: RU, zh: ZH, ja: JA };

function detect(): Lang {
  const nav = navigator.language.toLowerCase();
  return LANGS.find((l) => nav.startsWith(l)) ?? 'en';
}

let lang: Lang = detect();
document.documentElement.lang = lang;

export function currentLang(): Lang {
  return lang;
}

export function setLang(l: Lang | null): void {
  lang = l ?? detect();
  document.documentElement.lang = lang;
}

/** Texto en el idioma actual. `{nombre}` se sustituye por `vars.nombre`. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return TABLES[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export type TextKey = Key;
